#!/usr/bin/env python3
"""Extract a real-world Twitter snowflake ID benchmark dataset.

generate.py's snowflake_i64 dataset is a *simulation* of the field structure
(timestamp | machine id | sequence). This script instead samples real tweet
IDs from EncodingsPlayground/Datasets/TwitterSnowflake/tweet_ids.parquet
(30.7M rows), so the encoding is also measured against a real firehose capture
rather than only a synthetic one.

Written outside the repo, like generate.py's --out-dir mode: the sampled
dataset is tens of MB and is not committed.

Usage
-----
    python3 extract_real_snowflake.py --out-dir /tmp/sis-big --rows 1048576
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path

from generate import write_dataset

SOURCE_PARQUET = (
    Path(__file__).resolve().parents[4] / "EncodingsPlayground" / "Datasets" / "TwitterSnowflake" / "tweet_ids.parquet"
)


def load_tweet_ids() -> list[int]:
    import pyarrow.parquet as pq  # optional dependency, only needed for this script

    table = pq.read_table(SOURCE_PARQUET, columns=["tweet_id"])
    return table.column("tweet_id").to_pylist()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", type=Path, required=True, help="scratch directory to write snowflake_i64_real/ into")
    ap.add_argument("--rows", type=int, default=1_048_576, help="rows to sample (default 1048576)")
    ap.add_argument("--seed", type=int, default=7, help="sampling seed (default 7)")
    args = ap.parse_args()

    if not SOURCE_PARQUET.exists():
        raise SystemExit(f"real snowflake source not found: {SOURCE_PARQUET}")

    all_ids = load_tweet_ids()
    if args.rows > len(all_ids):
        raise SystemExit(f"--rows {args.rows} exceeds source size {len(all_ids)}")

    # A contiguous random slice, then sorted, preserves the source's real inter-arrival
    # structure (tweet IDs are roughly time-ordered) instead of shuffling it away.
    rng = random.Random(args.seed)
    start = rng.randint(0, len(all_ids) - args.rows)
    sample = sorted(all_ids[start : start + args.rows])

    write_dataset(
        args.out_dir / "snowflake_i64_real",
        sample,
        "FLS_I64",
        "- real Twitter snowflake IDs (not simulated)\n"
        f"- sampled {args.rows} consecutive rows (by source order) from a random offset,\n"
        f"  seed {args.seed}, out of 30761504 total rows, then sorted\n"
        "- source: EncodingsPlayground/Datasets/TwitterSnowflake/tweet_ids.parquet\n"
        "- generated by data/generated/subintsplit/extract_real_snowflake.py\n",
    )
    lo, hi = sample[0], sample[-1]
    print(f"snowflake_i64_real     rows={len(sample)} min={lo} max={hi} distinct={len(set(sample))}")


if __name__ == "__main__":
    main()
